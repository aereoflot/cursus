#include "libft.h"

void	*ft_memchr(const void *str, int c, size_t n)
{
	const unsigned char	*pnt;

	pnt = (const unsigned char *)str;
	while (n)
	{
		if (*pnt == (unsigned char)c)
			return ((void *)pnt);
		pnt++;
		n--;
	}
	return (NULL);
}
